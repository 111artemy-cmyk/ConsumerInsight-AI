"""Multi-seed stability evaluation script.

Run the full ConsumerInsight-AI pipeline with ``n_seeds`` distinct
RANDOM_SEED values and report the mean / std / min / max of the
headline metrics:

* Largest KMeans segment share (%)
* Peak illustrative ROI index value + its segment
* Worst funnel retention (excluding 100% Awareness) + its stage

Output
------
* ``outputs/reports/stability_report.md`` — Markdown summary table
* stdout — short summary

This script is intentionally a **separate entry point** from
``run_pipeline.py``: the main pipeline stays at ~5-10s, while this
script trades runtime for stability information. Default 10 seeds ×
1500 reviews takes ~1-2 minutes on a typical laptop.

Usage
-----
    python scripts/run_stability_eval.py                    # 10 seeds, n=1500
    python scripts/run_stability_eval.py --n-seeds 5 --n-reviews 500
    python scripts/run_stability_eval.py --seeds 1,7,42,100  # explicit seeds
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.evaluation import run_stability  # noqa: E402
from src.config import REPORTS_DIR  # noqa: E402


def main() -> int:
    p = argparse.ArgumentParser(
        description="Run multi-seed stability evaluation on the pipeline."
    )
    p.add_argument(
        "--n-seeds",
        type=int,
        default=10,
        help="Number of distinct seeds to run (default 10).",
    )
    p.add_argument(
        "--n-reviews",
        type=int,
        default=1500,
        help="Number of synthetic reviews per seed (default 1500).",
    )
    p.add_argument(
        "--seeds",
        type=str,
        default=None,
        help="Comma-separated explicit seed list, e.g. '1,7,42,100'. Overrides --n-seeds.",
    )
    p.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Override output markdown path (default outputs/reports/stability_report.md).",
    )
    args = p.parse_args()

    seeds = None
    if args.seeds is not None:
        seeds = [int(x.strip()) for x in args.seeds.split(",") if x.strip()]
        n_seeds = len(seeds)
    else:
        n_seeds = args.n_seeds
        seeds = None

    out_path = args.out or (REPORTS_DIR / "stability_report.md")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    print(
        f"[run_stability_eval] starting: n_seeds={n_seeds} n_reviews={args.n_reviews}"
    )
    t0 = time.time()
    report = run_stability(
        n_seeds=n_seeds,
        n_reviews=args.n_reviews,
        seeds=seeds,
    )
    dt = time.time() - t0
    print(f"[run_stability_eval] finished in {dt:.1f}s")

    # ----- Build markdown ---------------------------------------------
    runs_df_rows = [r.__dict__ for r in report.runs]
    import pandas as pd
    runs_df = pd.DataFrame(runs_df_rows)

    lines: list[str] = []
    a = lines.append
    a("# ConsumerInsight-AI — Multi-Seed Stability Report")
    a("")
    a(f"- n_seeds: **{n_seeds}**")
    a(f"- n_reviews per seed: **{args.n_reviews}**")
    a(f"- Wall time: **{dt:.1f}s**")
    a("")
    a("> " + report.disclosure)
    a("")
    a("## Headline metrics — summary")
    a("")
    # 数值 / 分类分别格式化
    summary_df = report.summary_by_metric.copy()

    def _fmt(v, is_str):
        if is_str:
            return v if isinstance(v, str) else str(v)
        if isinstance(v, str):
            return v
        return f"{v:.3f}"

    summary_df["mean"] = summary_df.apply(
        lambda r: _fmt(r["mean"], r["kind"] == "categorical"), axis=1
    )
    summary_df["std"] = summary_df.apply(
        lambda r: _fmt(r["std"], r["kind"] == "categorical"), axis=1
    )
    summary_df["min"] = summary_df.apply(
        lambda r: _fmt(r["min"], r["kind"] == "categorical"), axis=1
    )
    summary_df["max"] = summary_df.apply(
        lambda r: _fmt(r["max"], r["kind"] == "categorical"), axis=1
    )
    a(summary_df.to_markdown(index=False))
    a("")
    a("## Per-seed breakdown")
    a("")
    a(runs_df.to_markdown(index=False))
    a("")
    a("---")
    a("")
    a("*Generated by `scripts/run_stability_eval.py`. All numbers are real outputs from "
      f"{n_seeds} complete pipeline runs at distinct RANDOM_SEED values; nothing is fabricated.*")
    a("")

    out_path.write_text("\n".join(lines), encoding="utf-8")

    # ----- stdout summary ---------------------------------------------
    print(f"\n=== Multi-seed stability summary ({n_seeds} seeds × {args.n_reviews} reviews) ===")
    print(report.summary_by_metric.to_string(index=False))
    print(f"\nWritten to: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())